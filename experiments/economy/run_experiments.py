# ---- Experiment 14: per-case spending cap ---------------------------------------------------------------
MD.append("## Experiment 14. A per-case spending cap against late-case starvation (one Lock, no Trace)\n")
MD.append("The bank is still shared and never refills. The cap only limits how much Insight any single case may take. "
          "Spend per case is simulated (seed %d, 20,000 days).\n" % SEED)
R["e14"] = {}
rows = []
for pname, pack in PACKS.items():
    for cap in (None, 1, 2):
        v = var(tau=None, spend_cap=cap)
