// Timehunt service worker (ADR-001, OPERATIONS_POLICIES 6.2). Precached shell for offline play, network-first for the daily pack, a kill switch,
// and no forced takeover: a new version waits until the app is closed, so an update can never interrupt a case.
importScripts('sw-manifest.js'); // sets self.__BUILD, self.__PRECACHE, self.__KILL (generated by scripts/build-sw.mjs)
const CACHE = 'timehunt-' + self.__BUILD;
const PACK = /\/data\/[^/]+\.json$/;

self.addEventListener('install', e => {
  if (self.__KILL) return e.waitUntil(self.skipWaiting());
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(self.__PRECACHE.map(u => new Request(u, { cache: 'reload' })))));
});

self.addEventListener('activate', e => e.waitUntil((async () => {
  if (self.__KILL) {
    for (const k of await caches.keys()) await caches.delete(k);
    await self.registration.unregister();
    for (const c of await self.clients.matchAll({ type: 'window' })) c.navigate(c.url);
    return;
  }
  for (const k of await caches.keys()) if (k.startsWith('timehunt-') && k !== CACHE) await caches.delete(k);
  await self.clients.claim();
})()));

self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  if (self.__KILL || req.method !== 'GET' || url.origin !== location.origin) return;
  if (PACK.test(url.pathname)) {
    // The day's pack: prefer fresh, fall back to the last good copy so a day can be played offline.
    e.respondWith((async () => {
      try { const res = await fetch(req); if (res.ok) { (await caches.open(CACHE)).put(url.pathname, res.clone()); } return res; }
      catch (err) { const hit = await caches.match(url.pathname, { ignoreSearch: true }); if (hit) return hit; throw err; }
    })());
    return;
  }
  e.respondWith((async () => {
    const hit = await caches.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try { return await fetch(req); }
    catch (err) { if (req.mode === 'navigate') { const shell = await caches.match('index.html'); if (shell) return shell; } throw err; }
  })());
});
