// Generates app/sw-manifest.js: the list of files to precache and a build id (hash of their bytes), so any change to a shipped file
// produces a new cache. Usage: node scripts/build-sw.mjs [--kill]   (--kill writes a manifest whose worker removes itself and its caches)
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const INCLUDE_DIRS = ['src', 'fonts', 'assets', 'icons', 'data'];
const INCLUDE_FILES = ['index.html', 'ui.css', 'atlas.css', 'manifest.webmanifest'];
const SKIP = [/\/assets\/characters\/guide-master\.webp$/, /LICENSE/i, /\/src\/sim\//];   // archive copy, licence texts and dev-only simulator are not needed offline

function walk(dir) { return readdirSync(dir).flatMap(n => { const p = join(dir, n); return statSync(p).isDirectory() ? walk(p) : [p]; }); }
export function precacheList() {
  const files = [...INCLUDE_FILES.map(f => join(root, f)), ...INCLUDE_DIRS.flatMap(d => walk(join(root, d)))];
  return files.map(f => relative(root, f).split(sep).join('/')).filter(f => !SKIP.some(r => r.test('/' + f))).sort();
}
export function buildId(list) { const h = createHash('sha256'); for (const f of list) { h.update(f); h.update(readFileSync(join(root, f))); } return h.digest('hex').slice(0, 12); }
export function manifestText({ kill = false } = {}) {
  const list = precacheList();
  return `// Generated by scripts/build-sw.mjs. Do not edit.\nself.__BUILD = '${buildId(list)}';\nself.__KILL = ${kill};\nself.__PRECACHE = ${JSON.stringify(['./', ...list], null, 1)};\n`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const kill = process.argv.includes('--kill');
  writeFileSync(join(root, 'sw-manifest.js'), manifestText({ kill }));
  const list = precacheList();
  console.log(`sw-manifest.js: ${list.length} files, ${(list.reduce((n, f) => n + statSync(join(root, f)).size, 0) / 1024).toFixed(0)} KB, build ${buildId(list)}${kill ? ' (KILL SWITCH)' : ''}`);
}
