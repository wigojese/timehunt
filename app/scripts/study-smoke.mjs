// Study mode check on the Stage 7 UI. Usage: node scripts/study-smoke.mjs
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { start } from './serve.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/opt/node22/lib/node_modules/playwright');
const srv = await start(5198);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
await ctx.addInitScript(() => localStorage.setItem('timehunt:settings', JSON.stringify({ onboarded: true, textScale: 100, confirmSpend: true })));
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(String(e)));
const res = [];
const ok = (n, c) => { res.push([n, !!c]); if (!c) throw new Error('FAILED ' + n); };
await p.goto('http://127.0.0.1:5198/?study=P01&cond=B'); await p.waitForTimeout(700);
await p.locator('[data-action=trail-go]').click(); await p.locator('[data-action=to-hunt]').click(); await p.locator('[data-action=to-evidence]').click();
ok('condition B sells the relation as a Key link clue', (await p.locator('li.clue', { hasText: 'Key link' }).count()) === 1);
await p.locator('li.clue', { hasText: 'Key link' }).locator('button').click(); await p.getByRole('dialog').getByRole('button', { name: /^Reveal for/ }).click(); await p.waitForTimeout(200);
await p.locator('[data-action=to-hunt]').click();
await p.locator('#yr').evaluate(el => { el.value = 1969; el.dispatchEvent(new Event('input', { bubbles: true })); }); await p.getByRole('button', { name: /^Lock/ }).click(); await p.getByRole('dialog').getByRole('button', { name: /^Lock/ }).click(); await p.waitForTimeout(200);
await p.getByRole('button', { name: 'Today' }).click().catch(() => {});
await p.goto('http://127.0.0.1:5198/?study=P01&cond=B&r=1#/settings'); await p.waitForTimeout(600);
const [dl] = await Promise.all([p.waitForEvent('download'), p.locator('[data-action=dlstudy]').click()]);
const log = JSON.parse(readFileSync(await dl.path(), 'utf8'));
ok('log has participant and condition', log.participant === 'P01' && log.cond === 'B');
ok('log has timestamped view, reveal and lock events', ['view', 'reveal', 'lock'].every(k => log.events.some(e => e.e === k)) && log.events.every(e => typeof e.t === 'number'));
ok('lock event records correctness', log.events.some(e => e.e === 'lock' && e.correct === true));
ok('log holds no free text or answers', !JSON.stringify(log).includes('Concorde'));
await p.goto('http://127.0.0.1:5198/?study=P02&cond=A'); await p.waitForTimeout(700);
await p.locator('[data-action=trail-go]').click(); await p.locator('[data-action=to-hunt]').click();
ok('another participant starts fresh with 8 Insight, condition A (no Key link)', (await p.locator('.hudr').textContent()).includes('Insight 8 of 8'));
await p.locator('[data-action=to-evidence]').click();
ok('condition A has no Key link clue', (await p.locator('li.clue', { hasText: 'Key link' }).count()) === 0);
ok('no page errors', errs.length === 0);
await b.close(); srv.close();
console.log(`study smoke: ${res.filter(r => r[1]).length}/${res.length} passed`);
